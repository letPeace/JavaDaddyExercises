package java.mentorship.roadmap.Java_Core.step2_Base.topic2_Variables.task6_VariableComparison;

public class VariableComparison {
    public VariableComparison() {
    }

    public static void main(String[] args) {
        int a = 2;
        int b = 3;
        boolean greater = a > b;
        boolean less = a < b;
        boolean equal = a == b;
        System.out.println("a > b: " + greater);
        System.out.println("a < b: " + less);
        System.out.println("a = b: " + equal);
    }
}
